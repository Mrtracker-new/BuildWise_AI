"""Contract tests for the per-source fetch provenance schema.

The analysis response must carry a `data_sources` map with an ISO8601
fetched_at timestamp for every external data source consulted during the
analysis. A source that degraded to its deterministic fallback model reports
fetched_at=None with is_fallback=True — a missing timestamp is disclosed, never
silently backfilled, so the report UI never shows a fabricated fetch time.
"""
from datetime import datetime
from unittest.mock import patch

from fastapi.testclient import TestClient

from app.main import app

client = TestClient(app)


def _mock_http_response(url: str, **kwargs):
    import hashlib

    resp = type("Resp", (), {})()
    resp.status_code = 200

    def _json():
        if "nominatim" in url:
            return {
                "display_name": "Bengaluru Urban, Karnataka, India",
                "address": {"city": "Bengaluru", "state": "Karnataka"},
            }
        if "earthquake.usgs.gov" in url:
            return {"features": []}
        if "flood-api.open-meteo.com" in url:
            return {"daily": {"river_discharge": [0.02, 0.04, 0.01]}}
        if "archive-api.open-meteo.com" in url:
            times = [f"{y}-06-15" for y in range(2015, 2025)]
            return {
                "daily": {
                    "time": times,
                    "wind_gusts_10m_max": [55.0] * 10,
                    "precipitation_sum": [15.0] * 10,
                }
            }
        if "api.open-elevation.com" in url:
            return {"results": [{"elevation": 920.0}]}
        if "elevation-api" in url or "open-meteo.com/v1/elevation" in url:
            return {"elevation": [920.0, 921.0, 919.0, 920.5, 919.5]}
        if "api.open-meteo.com/v1/forecast" in url:
            return {
                "current": {
                    "temperature_2m": 28.0,
                    "wind_speed_10m": 12.0,
                    "wind_direction_10m": 240.0,
                },
                "daily": {
                    "temperature_2m_max": [32.0] * 7,
                    "temperature_2m_min": [20.0] * 7,
                    "precipitation_sum": [5.0] * 7,
                },
            }
        return {}

    resp.json = _json
    return resp


def _mock_http_post(url: str, **kwargs):
    resp = type("Resp", (), {})()
    resp.status_code = 200
    if "overpass-api.de" in url:
        resp.json = lambda: {
            "elements": [
                {
                    "geometry": [
                        {"lat": 12.972, "lon": 77.595},
                        {"lat": 12.973, "lon": 77.596},
                    ]
                }
            ]
        }
    else:
        resp.json = lambda: {}
    return resp


def _run_analyze():
    payload = {
        "latitude": 12.97,
        "longitude": 77.59,
        "built_up_area_sqft": 1200,
        "quality_grade": "standard",
        "building_typology": "residential_single",
        "floors": 1,
        "ai_provider": "mock",
    }
    with patch("httpx.AsyncClient.get", side_effect=_mock_http_response), patch(
        "httpx.AsyncClient.post", side_effect=_mock_http_post
    ):
        resp = client.post("/api/analyze", json=payload)
    assert resp.status_code == 200, resp.text
    return resp.json()


def test_analysis_response_includes_fetched_at_for_every_source():
    data = _run_analyze()
    ds = data.get("data_sources")
    assert isinstance(ds, dict), "data_sources provenance map missing from the response"
    expected_sources = {"geocode", "elevation", "climate", "road", "seismic", "flood", "storm_cyclone"}
    assert expected_sources.issubset(ds.keys()), f"missing source provenance: {expected_sources - set(ds.keys())}"
    for key, entry in ds.items():
        assert set(("source", "fetched_at", "is_fallback")).issubset(entry.keys()), f"{key} provenance shape wrong"
        if entry["is_fallback"]:
            assert entry["fetched_at"] is None, f"{key} is a fallback but claims a fetch time"
        else:
            ts = entry["fetched_at"]
            assert isinstance(ts, str) and ts, f"{key} fetched_at must be a non-empty ISO8601 string"
            # ISO8601-parseable (timezone-aware server timestamp)
            datetime.fromisoformat(ts.replace("Z", "+00:00"))


def test_fetched_at_values_are_real_server_timestamps_not_placeholders():
    data = _run_analyze()
    ds = data.get("data_sources", {})
    live = [e for e in ds.values() if not e["is_fallback"]]
    assert live, "expected at least one live source fetch in the mocked run"
    before = datetime.utcnow()
    after = datetime.utcnow()
    for e in live:
        ts = datetime.fromisoformat(e["fetched_at"].replace("Z", "+00:00")).replace(tzinfo=None)
        # The timestamp must fall inside the analysis window, proving it was
        # generated by the server during this request - not a hardcoded or
        # client-side placeholder.
        assert before - __import__("datetime").timedelta(seconds=5) <= ts <= after + __import__("datetime").timedelta(seconds=5)


def test_fallback_source_discloses_missing_timestamp():
    # Drop the Overpass post mock so the road lookup degrades to fallback.
    with patch("httpx.AsyncClient.get", side_effect=_mock_http_response), patch(
        "httpx.AsyncClient.post", side_effect=Exception("overpass down")
    ):
        resp = client.post(
            "/api/analyze",
            json={
                "latitude": 12.97,
                "longitude": 77.59,
                "built_up_area_sqft": 1200,
                "quality_grade": "standard",
                "building_typology": "residential_single",
                "floors": 1,
                "ai_provider": "mock",
            },
        )
    assert resp.status_code == 200, resp.text
    ds = resp.json().get("data_sources", {})
    road = ds.get("road")
    assert road is not None, "road provenance missing"
    assert road["is_fallback"] is True
    assert road["fetched_at"] is None, "fallback road source must disclose fetched_at=None"
